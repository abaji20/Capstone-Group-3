DROP POLICY IF EXISTS "Authenticated users can read library sections"
  ON public.library_sections;
CREATE POLICY "Authenticated users can read library sections"
  ON public.library_sections
  FOR SELECT
  TO authenticated
  USING (true);

DROP POLICY IF EXISTS "Admins can manage library sections"
  ON public.library_sections;
CREATE POLICY "Admins can manage library sections"
  ON public.library_sections
  FOR ALL
  TO authenticated
  USING (
    EXISTS (
      SELECT 1
      FROM public.profiles
      WHERE profiles.id = auth.uid()
        AND profiles.role IN ('admin', 'superadmin')
    )
  )
  WITH CHECK (
    EXISTS (
      SELECT 1
      FROM public.profiles
      WHERE profiles.id = auth.uid()
        AND profiles.role IN ('admin', 'superadmin')
    )
  );

GRANT SELECT, INSERT, UPDATE, DELETE ON public.library_sections TO authenticated;

CREATE TABLE IF NOT EXISTS public.deleted_pdf_archive (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_pdf_id text NOT NULL,
  pdf_data jsonb NOT NULL,
  deleted_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  deleted_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS deleted_pdf_archive_source_pdf_id_idx
  ON public.deleted_pdf_archive (source_pdf_id);

ALTER TABLE public.deleted_pdf_archive ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Admins can read deleted PDF archive"
  ON public.deleted_pdf_archive;
CREATE POLICY "Admins can read deleted PDF archive"
  ON public.deleted_pdf_archive
  FOR SELECT
  TO authenticated
  USING (
    EXISTS (
      SELECT 1
      FROM public.profiles
      WHERE profiles.id = auth.uid()
        AND profiles.role IN ('admin', 'superadmin')
    )
  );

DROP POLICY IF EXISTS "Admins can insert deleted PDF archive records"
  ON public.deleted_pdf_archive;
CREATE POLICY "Admins can insert deleted PDF archive records"
  ON public.deleted_pdf_archive
  FOR INSERT
  TO authenticated
  WITH CHECK (
    EXISTS (
      SELECT 1
      FROM public.profiles
      WHERE profiles.id = auth.uid()
        AND profiles.role IN ('admin', 'superadmin')
    )
  );

GRANT SELECT, INSERT ON public.deleted_pdf_archive TO authenticated;

